export const seedMissingCatalogFoods = async (centralRestaurantId) => {
  let seededCount = 0;
  for (const item of catalogDishes) {
    const existing = await foodModel.findOne({ name: item.name });
    if (!existing) {
      await foodModel.create({
        ...item,
        restaurantId: centralRestaurantId,
        prepTimeMinutes: item.prepTimeMinutes || 20,
        isAvailable: true
      });
      seededCount++;
    } else {
      // Ensure category, isVeg, and price are accurate
      let updated = false;
      if (existing.category !== item.category) {
        existing.category = item.category;
        updated = true;
      }
      if (existing.isVeg !== item.isVeg) {
        existing.isVeg = item.isVeg;
        updated = true;
      }
      if (existing.price !== item.price) {
        existing.price = item.price;
        updated = true;
      }
      if (existing.image !== item.image) {
        existing.image = item.image;
        updated = true;
      }
      if (updated) {
        await existing.save();
        console.log(`🖼️ [Catalog Sync] Updated dish "${existing.name}" image to: ${existing.image.slice(0, 45)}...`);
      }
    }
  }

  if (seededCount > 0) {
    console.log(`✅ [Migration] Seeded ${seededCount} new catalog dishes into MongoDB Atlas`);
  }
};
